"""Safe telemetry for one run: contracts, correlation, mapping, sinks, export.

Telemetry observes. It maps durable events the controller already wrote onto a
versioned record, correlates them into one causal timeline, writes that timeline
privately, and projects a sanitized public form of it. It never selects a tool,
scores a candidate, blocks an execution, authorizes a repair, decides an
outcome, or changes a terminal disposition.

Attaching a sink is the whole integration. With no sink the controller does no
telemetry work at all. A hosted container attaches `PublicLineSink`, so its
telemetry reaches the platform log in already-sanitized public form.
"""

